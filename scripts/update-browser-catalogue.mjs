// Rebuild runtime first. tools/list must never attach to a browser.
import { createServer } from "node:http";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import assert from "node:assert/strict";
import { format } from "prettier";
import { createPreviewMcpClient } from "../runtime/browser/mcp-client.mjs";
const entry = import.meta.resolve("chrome-devtools-mcp");
const version = JSON.parse(
  await readFile(new URL("../../package.json", entry), "utf8"),
).version;
assert.equal(version, "1.12.0");
const home = await mkdtemp(join(tmpdir(), "crew-browser-catalogue-"));
let connections = 0;
const server = createServer();
server.on("connection", (socket) => {
  connections++;
  socket.destroy();
});
let client;
try {
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  client = await createPreviewMcpClient({
    command: process.execPath,
    args: [fileURLToPath(new URL("./bin/chrome-devtools-mcp.js", entry))],
    endpoint: `ws://127.0.0.1:${server.address().port}/devtools/browser/catalogue-only`,
    env: { HOME: home, TMPDIR: home, PATH: "/usr/bin:/bin" },
  });
  const catalogue = await client.list();
  assert.equal(catalogue.length, 13);
  await client.close();
  client = undefined;
  assert.equal(
    connections,
    0,
    "Schema discovery attempted a browser connection",
  );
  const source =
    "// Generated by scripts/update-browser-catalogue.mjs from chrome-devtools-mcp@1.12.0 tools/list.\n" +
    "// No browser connection or launch is used. Do not hand-edit schemas.\n" +
    'import type { JsonObject } from "../agents/contracts.mjs";\n' +
    "export const pinnedBrowserCatalogue: {name: string; description?: string; inputSchema: JsonObject}[] = " +
    JSON.stringify(catalogue, null, 2) +
    ";\n";
  await writeFile(
    new URL("../src/browser/pinned-catalogue.mts", import.meta.url),
    await format(source, { parser: "typescript" }),
  );
  console.log("Generated 13 pinned schemas; browser connections: 0");
} finally {
  try {
    await client?.close();
  } finally {
    await new Promise((resolve) => server.close(resolve));
    await rm(home, { recursive: true, force: true });
  }
}
