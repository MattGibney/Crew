// GH-38: compiled renderer and genuine timeline projection, disposable backend only.
// No subscription or physical media; run npm run renderer:build first.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
const { chromium } = await import(process.env.CREW_PLAYWRIGHT_MODULE || 'playwright-core');
const port = Number(process.env.CREW_ACCEPTANCE_PORT || 4358), origin = `http://127.0.0.1:${port}`;
const output = await mkdtemp(path.join(tmpdir(), 'crew-chat-reconciliation-'));
const fixture = spawn(process.execPath, ['tests/browser-fixture.mjs', String(port)], { stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
// Register cleanup before the first observation; never touch another controller.
const cleanup = async () => { await browser?.close(); if (fixture.exitCode === null) { fixture.kill('SIGTERM'); await once(fixture, 'exit'); } };
try {
  await new Promise((resolve, reject) => { fixture.stdout.once('data', resolve); fixture.once('error', reject); fixture.once('exit', code => reject(Error(`Fixture exited ${code}`))); });
  browser = await chromium.launch({ headless: true, ...(process.env.CREW_BROWSER_EXECUTABLE ? { executablePath: process.env.CREW_BROWSER_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1400, height: 1000 } });
  const post = async body => { const response = await context.request.post(`${origin}/__control`, { data: body }); assert.equal(response.status(), 200); };
  const protocol = (method, params) => post({ protocol: { method, params } });
  const realtime = (type, id, role, text, completed = false) => protocol(`thread/realtime/item/${completed ? 'completed' : 'started'}`, { item: { type, id, role, text } });
  const native = (type, id, text, completed = false) => protocol(`item/${completed ? 'completed' : 'started'}`, { turnId: 'handoff-turn', item: type === 'userMessage' ? { type, id, content: [{ type: 'text', text }] } : { type, id, text, phase: 'final_answer' } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('tab', { name: 'Text', exact: true }).click();
  const draft = 'Keep this unsent draft through reconnect and reload.';
  await page.getByRole('textbox', { name: 'Message your manager', exact: true }).fill(draft);
  const row = id => page.locator(`article[data-message-id="${id}"]`);
  const request = 'Inspect the synthetic inventory.';
  await realtime('transcriptSegment', 'speech-user-1', 'user', 'Inspect');
  await protocol('thread/realtime/item/transcript/delta', { itemId: 'speech-user-1', delta: ' the synthetic inventory.' });
  await row('speech-user-1').waitFor();
  await page.waitForFunction(() => document.querySelector('article[data-message-id="speech-user-1"]')?.textContent.includes('the synthetic inventory.'));
  assert.match(await row('speech-user-1').textContent(), /Live/);
  await realtime('transcriptSegment', 'speech-user-1', 'user', request, true);
  await native('userMessage', 'native-user', `<realtime_delegation><input>${request}</input><transcript_delta>Earlier synthetic context.</transcript_delta></realtime_delegation>`, true);
  await native('agentMessage', 'native-answer', 'Verified written inventory: three synthetic records.');
  await protocol('item/agentMessage/delta', { itemId: 'native-answer', delta: ' One requires review.' });
  await native('agentMessage', 'native-answer', 'Verified written inventory: three synthetic records. One requires review.', true);
  await protocol('thread/realtime/item/completed', { item: { type: 'bemItemPromoted', id: 'promotion-fragment-1', itemId: 'native-answer' } });
  await protocol('thread/realtime/item/completed', { item: { type: 'bemItemPromoted', id: 'promotion-fragment-2', itemId: 'native-answer' } });
  await realtime('transcriptSegment', 'speech-answer', 'assistant', 'There are');
  await protocol('thread/realtime/item/transcript/delta', { itemId: 'speech-answer', delta: ' three records, with one to review.' });
  await row('speech-answer').waitFor();
  await page.waitForFunction(() => document.querySelector('article[data-message-id="speech-answer"]')?.textContent.includes('three records, with one to review.'));
  assert.match(await row('speech-answer').textContent(), /Live/);
  await realtime('transcriptSegment', 'speech-answer', 'assistant', 'There are three records, with one to review.', true);
  // A late callback cannot reopen the completed transcript or replace its text.
  await realtime('transcriptSegment', 'speech-answer', 'assistant', 'stale start');
  await protocol('thread/realtime/item/transcript/delta', { itemId: 'speech-answer', delta: ' stale delta' });
  await post({ work: { status: 'idle', activeTurnId: null } });
  await row('speech-answer').waitFor();
  await page.waitForFunction(() => { const row = document.querySelector('article[data-message-id="speech-answer"]'); return row?.textContent.includes('There are three records, with one to review.') && !row.textContent.includes('Live'); });
  await page.screenshot({ path: path.join(output, 'completed-conversation.png') });
  console.log(`GH-38 browser evidence: ${output}`);
  const details = page.locator('details[data-work-turn-id="handoff-turn"]');
  assert.equal(await details.count(), 1, 'Native voice backing exchange must be grouped into one Work details disclosure');
  assert.equal(await details.getAttribute('open'), null, 'Backing exchange is collapsed by default');
  assert.equal(await row('native-user').isVisible(), false, 'Voice work request does not duplicate the primary speech bubble');
  assert.equal(await row('native-answer').isVisible(), false, 'Written backing result remains secondary to the spoken response');
  assert.equal(await row('speech-user-1').count(), 1);
  assert.equal(await row('speech-answer').count(), 1);
  assert.doesNotMatch(await row('speech-answer').textContent(), /Live|stale/);
  await details.locator('summary').click();
  assert.match(await row('native-user').innerText(), /Voice work request/);
  assert.match(await row('native-answer').innerText(), /Written response/);
  assert.match(await row('native-answer').innerText(), /three synthetic records\. One requires review\./);
  await page.screenshot({ path: path.join(output, 'work-details.png') });
  await details.locator('summary').click();
  // Equal words with distinct canonical identities represent genuine repeats.
  await realtime('transcriptSegment', 'speech-user-2', 'user', request, true);
  await protocol('item/completed', { turnId: 'typed-turn', item: { type: 'userMessage', id: 'typed-user', content: [{ type: 'text', text: request }] } });
  await protocol('item/completed', { turnId: 'typed-turn', item: { type: 'agentMessage', id: 'typed-answer', text: 'Independent typed response stays in the primary timeline.' } });
  await row('typed-answer').waitFor();
  const expected = ['speech-user-1', 'native-user', 'native-answer', 'speech-answer', 'speech-user-2', 'typed-user', 'typed-answer'];
  const assertHistory = async () => {
    assert.deepEqual(await page.locator('article[data-message-id]').evaluateAll(rows => rows.map(row => row.dataset.messageId)), expected, 'Canonical order and distinct repeated messages survive reconciliation');
    for (const id of expected) assert.equal(await row(id).count(), 1, `Exactly one ${id}`);
    assert.equal(await page.locator('details[data-work-turn-id="handoff-turn"]').count(), 1);
    for (const id of ['speech-user-1', 'speech-answer', 'speech-user-2', 'typed-user', 'typed-answer']) assert.equal(await row(id).isVisible(), true);
    for (const id of ['speech-user-1', 'speech-user-2', 'typed-user']) assert.match(await row(id).textContent(), /Inspect the synthetic inventory\./);
    assert.match(await row('speech-answer').textContent(), /There are three records, with one to review\./);
    assert.match(await row('native-answer').textContent(), /Verified written inventory: three synthetic records\. One requires review\./);
    assert.doesNotMatch(await row('speech-answer').textContent(), /stale/);
    assert.doesNotMatch(await page.getByRole('region', { name: 'Manager conversation', exact: true }).innerText(), /· Live/);
    assert.equal(await page.evaluate(() => window.__crewMedia.calls), 0, 'No microphone capture requested');
  };
  await assertHistory();
  const beforeReconnect = (await (await context.request.get(`${origin}/__proof`)).json()).sseConnections;
  await post({ dropEvents: true });
  await page.waitForFunction(async previous => (await (await fetch('/__proof')).json()).sseConnections > previous, beforeReconnect);
  await assertHistory();
  assert.equal(await page.getByRole('textbox', { name: 'Message your manager', exact: true }).inputValue(), draft);
  // Round-trip the persisted projection through restore rather than inventing new IDs.
  const saved = (await (await context.request.get(`${origin}/__state`)).json()).work.messages;
  await post({ work: { messages: saved } });
  await page.reload();
  await row('typed-answer').waitFor();
  await assertHistory();
  await page.getByRole('tab', { name: 'Text', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Message your manager', exact: true }).inputValue(), draft);
  // Native work remains inspectable even when the provider supplies no speech.
  await protocol('item/completed', { turnId: 'silent-handoff-turn', item: { type: 'userMessage', id: 'silent-native-user', content: [{ type: 'text', text: '<realtime_delegation><input>Inspect the silent synthetic case.</input></realtime_delegation>' }] } });
  await protocol('item/completed', { turnId: 'silent-handoff-turn', item: { type: 'agentMessage', id: 'silent-native-answer', text: 'Written evidence remains available when speech is absent.' } });
  const silentDetails = page.locator('details[data-work-turn-id="silent-handoff-turn"]');
  await silentDetails.waitFor();
  await silentDetails.locator('summary').click();
  assert.equal(await row('silent-native-user').isVisible(), true);
  assert.equal(await row('silent-native-answer').isVisible(), true);
  assert.match(await row('silent-native-answer').innerText(), /Written evidence remains available when speech is absent\./);
  await page.setViewportSize({ width: 440, height: 900 });
  await row('silent-native-answer').scrollIntoViewIfNeeded();
  assert.equal(await row('silent-native-answer').isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), true, 'Narrow conversation does not overflow horizontally');
  await page.screenshot({ path: path.join(output, 'narrow-written-evidence.png') });
  assert.equal(await page.evaluate(() => window.__crewMedia.calls), 0);
  const proof = await (await context.request.get(`${origin}/__proof`)).json();
  assert.equal(proof.calls.filter(call => ['work', 'connect', 'voice-ready'].includes(call.name)).length, 0, 'Projection cannot launch model work or voice');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ pass: true, output, streamingFinal: true, backingDisclosure: true, repeatedMessages: true, persistedRestore: true, reconnect: true, reload: true, draftPreserved: true, absentSpeechEvidence: true, narrowView: true, mediaCalls: 0, syntheticOnly: true }));
} finally { await cleanup(); }
